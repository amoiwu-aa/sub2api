func TestCookiesForURLFiltersScopeExpiryAndKeepsChunks(t *testing.T) {
	now := time.Unix(1_800_000_000, 0).UTC()
	target, _ := url.Parse(DefaultSessionEndpoint)
	cookies := []browserCookie{
		{
			Domain: ".chatgpt.com", Path: "/", Secure: true,
			Name: "__Secure-authjs.session-token.1", Value: "part-1",
			ExpiresAt: now.Add(time.Hour).Unix(),
		},
		{
			Domain: ".chatgpt.com", Path: "/", Secure: true,
			Name: "__Secure-authjs.session-token.0", Value: "part-0",
			ExpiresAt: now.Add(time.Hour).Unix(),
		},
		{
			Domain: ".chatgpt.com", Path: "/", Secure: true,
			Name: "__Secure-authjs.session-token.10", Value: "part-10",
			ExpiresAt: now.Add(time.Hour).Unix(),
		},
		{
			Domain: ".chatgpt.com", Path: "/", Secure: true,
			Name: "__Secure-authjs.session-token.2", Value: "part-2",
			ExpiresAt: now.Add(time.Hour).Unix(),
		},
		{
			Domain: ".chatgpt.com", Path: "/", Secure: true,
			Name: "cf_clearance", Value: "clearance",
			ExpiresAt: now.Add(time.Hour).Unix(),
		},
		{
			Domain: ".chatgpt.com", Path: "/", Secure: true,
			Name: "expired", Value: "old",
			ExpiresAt: now.Add(-time.Second).Unix(),
		},
		{
			Domain: ".example.com", Path: "/", Secure: true,
			Name: "unrelated", Value: "wrong-domain",
			ExpiresAt: now.Add(time.Hour).Unix(),
		},
		{
			Domain: ".chatgpt.com", Path: "/backend-api", Secure: true,
			Name: "wrong-path", Value: "not-for-session",
			ExpiresAt: now.Add(time.Hour).Unix(),
		},
	}

	filtered, err := cookiesForURL(cookies, target, now)
	if err != nil {
		t.Fatalf("cookiesForURL: %v", err)
	}
	header, err := buildCookieHeader(filtered)
	if err != nil {
		t.Fatalf("buildCookieHeader: %v", err)
	}
	for _, want := range []string{
		"__Secure-authjs.session-token.0=part-0",
		"__Secure-authjs.session-token.1=part-1",
		"__Secure-authjs.session-token.2=part-2",
		"__Secure-authjs.session-token.10=part-10",
		"cf_clearance=clearance",
	} {
		if !strings.Contains(header, want) {
			t.Errorf("header missing %q: %s", want, header)
		}
	}
	for _, notWant := range []string{"expired", "wrong-domain", "wrong-path"} {
		if strings.Contains(header, notWant) {
			t.Errorf("header should not contain %q: %s", notWant, header)
		}
	}
	if strings.Index(header, ".0=part-0") > strings.Index(header, ".1=part-1") {
		t.Fatalf("chunk order is wrong: %s", header)
	}
	if strings.Index(header, ".2=part-2") > strings.Index(header, ".10=part-10") {
		t.Fatalf("multi-digit chunk order is wrong: %s", header)
	}
}

func TestSessionCookieFamilyOnlyAcceptsNumericChunks(t *testing.T) {
	for _, name := range []string{
		"__Secure-next-auth.session-token",
		"__Secure-next-auth.session-token.0",
		"authjs.session-token.12",
	} {
		if !isSessionCookie(name) {
			t.Errorf("should recognize %q", name)
		}
	}
	for _, name := range []string{
		"__Secure-next-auth.csrf-token",
		"__Secure-next-auth.session-token.bad",
		"prefix__Secure-next-auth.session-token",
	} {
		if isSessionCookie(name) {
			t.Errorf("should not recognize %q", name)
		}
	}
}

