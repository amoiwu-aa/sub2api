func TestParseCookieInputSupportsCookieEditorFormats(t *testing.T) {
	tests := []struct {
		name       string
		input      string
		wantFormat string
		wantDomain string
	}{
		{
			name: "json",
			input: `[
				{
					"domain": ".chatgpt.com",
					"expirationDate": 1999999999.75,
					"hostOnly": false,
					"name": "__Secure-next-auth.session-token",
					"path": "/",
					"secure": true,
					"value": "json-token"
				}
			]`,
			wantFormat: "Cookie-Editor JSON",
			wantDomain: ".chatgpt.com",
		},
		{
			name: "netscape",
			input: strings.Join([]string{
				"# Netscape HTTP Cookie File",
				"# This file was generated by Cookie-Editor",
				"#HttpOnly_.chatgpt.com\tTRUE\t/\tTRUE\t1999999999\t__Secure-next-auth.session-token\tnetscape-token",
			}, "\n"),
			wantFormat: "Netscape",
			wantDomain: ".chatgpt.com",
		},
		{
			name:       "header",
			input:      "cookie: __Secure-next-auth.session-token=header-token; cf_clearance=clearance",
			wantFormat: "Header String",
			wantDomain: "",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			cookies, format, err := parseCookieInput([]byte(tc.input))
			if err != nil {
				t.Fatalf("parseCookieInput: %v", err)
			}
			if format != tc.wantFormat {
				t.Fatalf("format = %q, want %q", format, tc.wantFormat)
			}
			if len(cookies) == 0 {
				t.Fatal("no cookies parsed")
			}
			if cookies[0].Domain != tc.wantDomain {
				t.Fatalf("domain = %q, want %q", cookies[0].Domain, tc.wantDomain)
			}
			if !isSessionCookie(cookies[0].Name) {
				t.Fatalf("session cookie not recognized: %q", cookies[0].Name)
			}
		})
	}
}

func TestParseJSONCookiesSupportsWrapperAndSingleCookie(t *testing.T) {
	wrapped, err := parseJSONCookies([]byte(`{
		"cookies": [
			{"domain": ".chatgpt.com", "name": "__Secure-authjs.session-token.0", "value": "part-0"}
		]
	}`))
	if err != nil {
		t.Fatalf("parse wrapped: %v", err)
	}
	if len(wrapped) != 1 || wrapped[0].Value != "part-0" {
		t.Fatalf("wrapped = %#v", wrapped)
	}

	single, err := parseJSONCookies([]byte(
		`{"domain":".chatgpt.com","name":"next-auth.session-token","value":"single"}`,
	))
	if err != nil {
		t.Fatalf("parse single: %v", err)
	}
	if len(single) != 1 || single[0].Value != "single" {
		t.Fatalf("single = %#v", single)
	}
}

