func TestConvertBuildsSanitizedImportCredential(t *testing.T) {
	now := time.Date(2026, 8, 3, 6, 0, 0, 0, time.UTC)
	expiry := now.Add(2 * time.Hour)
	accessToken := testJWT(t, expiry)
	const cookieSecret = "browser-session-secret"
	const responseSessionSecret = "must-not-be-exported"

	var gotCookie, gotUA, gotReferer string
	client := &http.Client{Transport: roundTripFunc(func(r *http.Request) (*http.Response, error) {
		gotCookie = r.Header.Get("Cookie")
		gotUA = r.Header.Get("User-Agent")
		gotReferer = r.Header.Get("Referer")
		body := fmt.Sprintf(`{
			"user":{"id":"user-1","name":"Tester","email":"person@example.com","private":"drop-me"},
			"account":{"id":"acct-1","planType":"plus","private":"drop-me"},
			"accessToken":%q,
			"sessionToken":%q,
			"expires":"2026-08-10T00:00:00Z",
			"authProvider":"auth0"
		}`, accessToken, responseSessionSecret)
		return &http.Response{
			StatusCode: http.StatusOK,
			Header:     make(http.Header),
			Body:       io.NopCloser(strings.NewReader(body)),
			Request:    r,
		}, nil
	})}

	result, err := Convert(
		context.Background(),
		client,
		[]byte("__Secure-next-auth.session-token="+cookieSecret+"; cf_clearance=ok"),
		Options{Now: now, UserAgent: "test-agent"},
	)
	if err != nil {
		t.Fatalf("Convert: %v", err)
	}
	if gotCookie != "__Secure-next-auth.session-token="+cookieSecret+"; cf_clearance=ok" {
		t.Fatalf("Cookie = %q", gotCookie)
	}
	if gotUA != "test-agent" {
		t.Fatalf("User-Agent = %q", gotUA)
	}
	if gotReferer != "https://chatgpt.com/" {
		t.Fatalf("Referer = %q", gotReferer)
	}
	if !result.TokenExpiresAt.Equal(expiry) {
		t.Fatalf("expiry = %s, want %s", result.TokenExpiresAt, expiry)
	}
	if result.Credential.AccessToken != accessToken ||
		result.Credential.ExpiresAt != expiry.Format(time.RFC3339) {
		t.Fatalf("credential token/expiry mismatch: %#v", result.Credential)
	}
	if result.Credential.User["email"] != "person@example.com" ||
		result.Credential.Account["planType"] != "plus" {
		t.Fatalf("identity not retained: %#v", result.Credential)
	}
	if _, ok := result.Credential.User["private"]; ok {
		t.Fatalf("unknown user field retained: %#v", result.Credential.User)
	}

	encoded, err := json.Marshal(result.Credential)
	if err != nil {
		t.Fatal(err)
	}
	for _, secret := range []string{cookieSecret, responseSessionSecret, "drop-me"} {
		if strings.Contains(string(encoded), secret) {
			t.Fatalf("credential leaked %q: %s", secret, encoded)
		}
	}
}

func TestConvertDisablesRedirectsWithoutMutatingSharedClient(t *testing.T) {
	var targetHits int
	client := &http.Client{
		Transport: roundTripFunc(func(r *http.Request) (*http.Response, error) {
			if r.URL.Host == "evil.example" {
				targetHits++
			}
			return &http.Response{
				StatusCode: http.StatusFound,
				Header:     http.Header{"Location": []string{"https://evil.example/steal"}},
				Body:       io.NopCloser(strings.NewReader("redirect")),
				Request:    r,
			}, nil
		}),
		CheckRedirect: func(_ *http.Request, _ []*http.Request) error {
			t.Fatal("the caller's redirect policy must not be invoked")
			return nil
		},
	}

	_, err := Convert(
		context.Background(),
		client,
		[]byte("__Secure-next-auth.session-token=secret"),
		Options{Now: time.Now()},
	)
	if err == nil || KindOf(err) != ErrorSessionRejected {
		t.Fatalf("redirect should be rejected, got: %v", err)
	}
	if targetHits != 0 {
		t.Fatalf("redirect target was requested %d times", targetHits)
	}
	if client.CheckRedirect == nil {
		t.Fatal("shared client was mutated")
	}
}

func TestExchangeSessionDoesNotLeakErrorBody(t *testing.T) {
	const canary = "response-body-secret"
	client := &http.Client{Transport: roundTripFunc(func(r *http.Request) (*http.Response, error) {
		return &http.Response{
			StatusCode: http.StatusForbidden,
			Header:     make(http.Header),
			Body:       io.NopCloser(strings.NewReader(`{"secret":"` + canary + `"}`)),
			Request:    r,
		}, nil
	})}
	endpoint, _ := url.Parse(DefaultSessionEndpoint)
	_, _, err := exchangeSession(
		context.Background(),
		client,
		endpoint,
		"session=secret",
		"test-agent",
		time.Now(),
	)
	if err == nil {
		t.Fatal("403 should fail")
	}
	if strings.Contains(err.Error(), canary) {
		t.Fatalf("error leaked response body: %v", err)
	}
	if KindOf(err) != ErrorSessionRejected {
		t.Fatalf("kind = %q", KindOf(err))
	}
}

