func TestConvertRejectsOversizedUserAgentBeforeSendingCookies(t *testing.T) {
	called := false
	client := &http.Client{Transport: roundTripFunc(func(r *http.Request) (*http.Response, error) {
		called = true
		return nil, errors.New("unexpected request")
	})}
	_, err := Convert(
		context.Background(),
		client,
		[]byte("__Secure-next-auth.session-token=secret"),
		Options{UserAgent: strings.Repeat("x", MaxUserAgentBytes+1)},
	)
	if err == nil || KindOf(err) != ErrorInvalidInput {
		t.Fatalf("oversized User-Agent should be invalid, got %v", err)
	}
	if called {
		t.Fatal("cookies were sent before User-Agent validation")
	}
}

type roundTripFunc func(*http.Request) (*http.Response, error)

func (f roundTripFunc) RoundTrip(req *http.Request) (*http.Response, error) {
	return f(req)
}

func testJWT(t *testing.T, expiry time.Time) string {
	t.Helper()
	header, err := json.Marshal(map[string]any{"alg": "none", "typ": "JWT"})
	if err != nil {
		t.Fatal(err)
	}
	body, err := json.Marshal(map[string]any{"exp": expiry.Unix()})
	if err != nil {
		t.Fatal(err)
	}
	return base64.RawURLEncoding.EncodeToString(header) + "." +
		base64.RawURLEncoding.EncodeToString(body) + ".signature"
}
